import streamlit as st
import pandas as pd
import numpy as np
import xgboost as xgb
import shap
import matplotlib.pyplot as plt

# Set page layout to wide for dashboard feel
st.set_page_config(layout="wide", page_title="Italian FMCG Operations MVP")

st.title("🇮🇹 AI Retail Operations Co-Pilot (MVP Proof of Concept)")
st.caption("Methodological limitation: This prototype is a limited-scope proof of concept, not a production-ready system.")

# ==========================================
# STEP 1: GENERATE SYNTHETIC ITALIAN FMCG DATA
# ==========================================
@st.cache_data
def load_synthetic_data():
    np.random.seed(42)
    days = 100

    # Simulating data for a high-volume category: "Pasta di Semola" (e.g., Barilla/De Cecco)
    data = {
        'Price_Euro': np.random.uniform(0.99, 1.89, days),
        'Competitor_Price_Euro': np.random.uniform(0.89, 1.99, days),
        'Is_Promo_Volantino': np.random.choice([0, 1], size=days, p=[0.7, 0.3]), # In-flyer promo
        'In_Store_Display': np.random.choice([0, 1], size=days, p=[0.8, 0.2]), # Island/Endcap placement
        'Temperature_C': np.random.uniform(5, 32, days),
        'Is_Weekend': np.random.choice([0, 1], size=days, p=[5/7, 2/7])
    }

    df = pd.DataFrame(data)

    # Ground truth formula for baseline Sales Vol (with some random noise)
    df['Sales_Volume'] = (
        1500
        - (df['Price_Euro'] * 400)
        + ((df['Competitor_Price_Euro'] - df['Price_Euro']) * 200)
        + (df['Is_Promo_Volantino'] * 600)
        + (df['In_Store_Display'] * 350)
        + (df['Is_Weekend'] * 400)
        + np.random.normal(0, 50, days)
    ).astype(int)

    return df

df = load_synthetic_data()

# ==========================================
# STEP 2: TRAIN PREDICTIVE MODEL (XGBOOST)
# ==========================================
X = df.drop(columns=['Sales_Volume'])
y = df['Sales_Volume']

model = xgb.XGBRegressor(n_estimators=50, max_depth=3, random_state=42)
model.fit(X, y)

# ==========================================
# STEP 3: GENERATE SHAP EXPLANATIONS
# ==========================================
explainer = shap.TreeExplainer(model)
shap_values = explainer(X)

# Layout: Split dashboard into Sidebar (Controls) and Main Panel (Outputs)
st.sidebar.header("🕹️ Scenario Simulation Controls")
st.sidebar.write("Adjust the current store parameters to see the AI Agent cycle respond:")

# User inputs to test scenarios for today's forecast
s_price = st.sidebar.slider("Our Price (€)", 0.50, 2.50, 1.29)
s_comp_price = st.sidebar.slider("Competitor Price (€)", 0.50, 2.50, 1.19)
s_promo = st.sidebar.selectbox("Featured in 'Volantino' (Flyer)?", ["No", "Yes"])
s_display = st.sidebar.selectbox("Special In-Store Display?", ["No", "Yes"])
s_temp = st.sidebar.slider("Temperature Forecast (°C)", 0, 40, 22)
s_weekend = st.sidebar.selectbox("Is it a Weekend?", ["No", "Yes"])

# Map inputs back to model format
input_data = pd.DataFrame([{
    'Price_Euro': s_price,
    'Competitor_Price_Euro': s_comp_price,
    'Is_Promo_Volantino': 1 if s_promo == "Yes" else 0,
    'In_Store_Display': 1 if s_display == "Yes" else 0,
    'Temperature_C': s_temp,
    'Is_Weekend': 1 if s_weekend == "Yes" else 0
}])

# Predict for the custom scenario
predicted_sales = int(model.predict(input_data)[0])
instance_shap = explainer(input_data)

# Extract top contributing factors for this specific instance
feature_names = X.columns
shap_impacts = instance_shap.values[0]
base_value = instance_shap.base_values[0]

# Pair feature names with their raw impact value
impact_df = pd.DataFrame({
    'Feature': feature_names,
    'Impact': shap_impacts,
    'Abs_Impact': np.abs(shap_impacts)
}).sort_values(by='Abs_Impact', ascending=False)

# ==========================================
# MAIN INTERFACE OUTPUTS
# ==========================================
col1, col2 = st.columns([1, 2])

with col1:
    st.metric(label="📊 Forecasted Daily Sales Volume", value=f"{predicted_sales} Units", delta=f"{int(predicted_sales - y.mean())} vs Avg")

    # Clean feature names for presentation
    clean_labels = {
        'Price_Euro': 'Our Retail Price',
        'Competitor_Price_Euro': 'Competitor Price Index',
        'Is_Promo_Volantino': 'Flyer Promotion Active',
        'In_Store_Display': 'Endcap/Island Display',
        'Temperature_C': 'Local Temperature',
        'Is_Weekend': 'Weekend Traffic Spike'
    }

    # ==========================================
    # STEP 4: TRANSLATE TO NATURAL LANGUAGE (NLG)
    # ==========================================
    st.subheader("🤖 Agent Explanation (NLG)")

    top_factor_raw = impact_df.iloc[0]['Feature']
    top_factor_name = clean_labels[top_factor_raw]
    top_factor_direction = "positively" if impact_df.iloc[0]['Impact'] > 0 else "negatively"

    second_factor_raw = impact_df.iloc[1]['Feature']
    second_factor_name = clean_labels[second_factor_raw]
    second_factor_direction = "positively" if impact_df.iloc[1]['Impact'] > 0 else "negatively"

    nlg_template = f"""
    The forecasting agent predicts a volume of **{predicted_sales} units** for the 'Pasta' category today.

    The primary driver behind this forecast is **{top_factor_name}**, which is impacting demand **{top_factor_direction}**.
    The secondary driving factor is **{second_factor_name}**, driving the trajectory **{second_factor_direction}**.
    """
    st.write(nlg_template)

    # ==========================================
    # STEP 5: AUTOMATED ACTIONABLE RECOMMENDATION
    # ==========================================
    st.subheader("💡 Autonomous Recommendation")

    # Simple decision-rule engine mapping top SHAP factors to specific operations
    if top_factor_raw == 'Price_Euro' and impact_df.iloc[0]['Impact'] < 0:
        recommendation = "⚠️ **Action:** Price Elasticity Alert. Our current price is bottlenecking volume. Recommend activating a flash 10% discount or bundle offer."
    elif top_factor_raw == 'Competitor_Price_Euro' and s_price > s_comp_price:
        recommendation = "⚔️ **Action:** Competitor Under-cutting. The rival store has priced lower. Initiate a price-match strategy or clear aisle signage highlighting premium quality."
    elif top_factor_raw == 'Is_Promo_Volantino' and s_promo == "Yes":
        recommendation = "📦 **Action:** Supply Chain Prep. The flyer promotion is aggressively driving volume. Alert the warehouse team to increase backroom safety stock by 20% to prevent shelf stockouts."
    elif top_factor_raw == 'In_Store_Display' and s_display == "No":
        recommendation = "🗺️ **Action:** Merchandising Opportunity. Sales would benefit heavily from physical real estate. Request floor staff move this stock to a high-traffic cross-merchandising zone."
    elif top_factor_raw == 'Is_Weekend' and s_weekend == "Yes":
        recommendation = "👥 **Action:** HR / Workforce Optimization. Weekend traffic is heavily inflating demand. Ensure checkout lanes and floor restocking shifts are fully staffed between 10:00 and 18:00."
    else:
        recommendation = "✅ **Action:** Maintain current operational standards. Monitor sales volume pacing over the next 4 hours."

    st.info(recommendation)

with col2:
    st.subheader("🔍 Underlying SHAP Factor Breakdown")
    st.write("This chart details exactly how many units each operational factor added or subtracted from the store's baseline sales level.")

    # Plotting simplified SHAP chart using Matplotlib
    fig, ax = plt.subplots(figsize=(6, 4))
    display_df = impact_df.copy()
    display_df['CleanName'] = display_df['Feature'].map(clean_labels)

    colors = ['#ff0051' if x < 0 else '#008bfb' for x in display_df['Impact']]
    ax.barh(display_df['CleanName'], display_df['Impact'], color=colors)
    ax.axvline(x=0, color='black', linestyle='--', linewidth=0.8)
    ax.set_xlabel('Impact on Sales Volume (Units)')
    plt.tight_layout()

    st.pyplot(fig)

    # Show clean raw data matrix for the transparency survey step
    st.subheader("📋 Underlying Live Data Record")
    st.dataframe(input_data.rename(columns=clean_labels))
